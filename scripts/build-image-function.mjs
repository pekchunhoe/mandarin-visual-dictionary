import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const license = await readFile('public/data/WORDNET-LICENSE.txt', 'utf8');
const result = await build({ entryPoints: ['server/image-handler.ts'], outfile: 'server/image-service.mjs', bundle: true, platform: 'node', format: 'esm', target: 'node24', legalComments: 'none', minify: true, metafile: true,
  banner: { js: `// Generated by scripts/build-image-function.mjs. Do not edit.\n/*\n${license}*/` } });
assert(result.metafile.inputs['src/data/visual-lexicon.json'], 'WordNet lexicon must be embedded in the native bundle');
assert(result.metafile.inputs['src/data/visual-templates.json'], 'English visual templates must be embedded in the native bundle');
assert(result.metafile.inputs['src/data/concept-templates.json'], 'English concept templates must be embedded in the native bundle');
for (const output of Object.values(result.metafile.outputs)) {
  assert(output.imports.every(item => item.path.startsWith('node:')), 'Runtime dependencies must be native Node built-ins only');
  assert(output.bytes < 1_000_000, 'Image function unexpectedly exceeds 1 MB');
}
console.log('PASS: native Node image function bundled with shared sense inference and server-only provider adapters.');
