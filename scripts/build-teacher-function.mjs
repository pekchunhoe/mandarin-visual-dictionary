import { build } from 'esbuild';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const license = await readFile('public/data/WORDNET-LICENSE.txt', 'utf8');
const result = await build({ entryPoints: ['server/teacher-handler.ts'], outfile: 'server/teacher-service.mjs', bundle: true, platform: 'node', format: 'esm', target: 'node24', legalComments: 'none', minify: true, metafile: true,
  banner: { js: `// Generated by scripts/build-teacher-function.mjs. Do not edit.\n/*\n${license}*/` } });
for (const output of Object.values(result.metafile.outputs)) {
  assert(output.imports.every(item => item.path.startsWith('node:')), 'Teacher runtime must bundle all dependencies');
  assert(output.bytes < 1_000_000, 'Teacher function unexpectedly exceeds 1 MB');
}
console.log('PASS: AI Teacher bundled for native Node; credentials remain runtime-only.');
