import { chromium, expect } from '@playwright/test';
import { writeFileSync } from 'node:fs';
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge' });
const context = await browser.newContext();
const requests = [], errors = [];
context.on('request', request => requests.push(request.url()));
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
try {
  await page.route('**/api/images?**', route => route.fulfill({ json: { status: 'unavailable', images: [] } }));
  await page.goto('http://127.0.0.1:4173/');
  await expect(page.locator('.hero')).toBeVisible();
  await page.evaluate(() => navigator.serviceWorker.ready);
  expect(requests.filter(url => /malay-runtime.*\.json/.test(url))).toHaveLength(0);
  expect(requests.filter(url => url.endsWith('/data/cedict.json'))).toHaveLength(0);
  const start = Date.now();
  await page.goto('http://127.0.0.1:4173/#search=mendidih');
  const card = page.locator('.word-card-main').filter({ has: page.getByRole('heading', { name: '开', exact: true }) }).first();
  await expect(card).toBeVisible({ timeout: 30000 });
  const firstLookupMs = Date.now() - start;
  const malayFetches = requests.filter(url => /malay-runtime.*\.json/.test(url)).length;
  expect(malayFetches).toBeGreaterThan(0);
  await card.click();
  await expect(page.locator('.meaning-panel p[lang="en"]')).toHaveText('to boil');
  await expect(page.locator('.meaning-panel p[lang="ms"]')).toHaveText('mendidih');
  await page.getByRole('button', { name: 'Save word', exact: true }).click();
  const saved = await page.evaluate(() => [localStorage.getItem('kanjian-saved'), localStorage.getItem('kanjian-saved-entries')]);
  await context.setOffline(true); await page.reload();
  await expect(page.locator('.meaning-panel p[lang="en"]')).toHaveText('to boil', { timeout: 30000 });
  await expect(page.locator('.meaning-panel p[lang="ms"]')).toHaveText('mendidih');
  expect(await page.evaluate(() => [localStorage.getItem('kanjian-saved'), localStorage.getItem('kanjian-saved-entries')])).toEqual(saved);
  await page.goto('http://127.0.0.1:4173/#search=' + encodeURIComponent('tidak malu bertanya'));
  await expect(page.getByRole('heading', { name: '不耻下问', exact: true })).toBeVisible({ timeout: 30000 });
  await page.goto('http://127.0.0.1:4173/#search=menolong');
  await expect(page.getByRole('heading', { name: '帮助', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
  const report = { productionOfflinePass: true, firstLookupMs, freshHomeMalayFetches: 0, freshHomeDictionaryFetches: 0, savedSenseRetained: true, phraseAndSynonymOffline: true, pageErrors: errors };
  writeFileSync('.tmp/malay-offline.json', JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify(report, null, 2));
} finally { await context.close(); await browser.close(); }
